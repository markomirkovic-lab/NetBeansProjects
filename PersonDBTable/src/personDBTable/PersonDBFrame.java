    private void orderButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_orderButtonActionPerformed
        // Order by.
         // Ottieni il DefaultTableModel della JTable ed elimina tutte le row
        // della JTable (verranno sostituite dai nuovi dati nel DB).
        DefaultTableModel dtm = (DefaultTableModel) this.personDataTable.getModel();
        dtm.setRowCount(0);

        try ( Statement stmt = this.conn.createStatement()) {
            // Esegui la SELECT e inserisci le row del DB nella JTable.
            String comboBox = this.orderComboBox.getSelectedItem().toString();
            System.out.println(comboBox);
            String query = "SELECT * FROM person ORDER BY " + comboBox + " ";
            query += (this.ascRadioButton.isSelected()) ? "ASC" : "DESC";
            System.out.println(query);
            try ( ResultSet rs = stmt.executeQuery(query)) {
                // Itera il resultSet.
                while (rs.next()) {
                    // Imposta l'array di Object con i dati della row da inserire.
                    // Un elemento Object può essere impostato direttamente con
                    // qualsiasi tipo di dato, questa operazione si chiama "boxing".
                    // L
                    Object[] rowData = {
                        new IdFirstnameItem(rs.getInt("id"),
                        rs.getString("firstname")),
                        rs.getString("lastname"),
                        rs.getString("email"),
                        rs.getString("address")
                    };

                    // Inserisci la nuova row.
                    dtm.addRow(rowData);
                }
            }

            // Aggiorna lo stato della GUI, dato che la JTable è stata svuotata
            // e poi ripopolata, una sua eventuale row-selection è andata persa.
            this.updateGUI();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage(),
                    "Person List",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_orderButtonActionPerformed

