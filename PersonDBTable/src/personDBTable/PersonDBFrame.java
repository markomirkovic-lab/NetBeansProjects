    private void insertButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertButtonActionPerformed
        // Inserisci una nuova row nel database.
        String sql = "INSERT INTO person (firstname, lastname, email, address)"
                + " VALUES(?, ?, ?, ?)";
        try ( PreparedStatement pstmt = this.conn.prepareStatement(sql)) {
            // Sostituisci i quattro place-holder con i valori stringa dei
            // relativi JTextField.
            pstmt.setString(1, this.firstnameTextField.getText());
            pstmt.setString(2, this.lastnameTextField.getText());
            pstmt.setString(3, this.emailTextField.getText());
            pstmt.setString(4, this.addressTextField.getText());

            // Esegui la query di INSERT.
            pstmt.executeUpdate();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage(),
                    "Person List",
                    JOptionPane.ERROR_MESSAGE);
        }

        // Aggiorna il contenuto della JTable (con i nuovi dati del DB).
        this.refreshTableContent();
    }//GEN-LAST:event_insertButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        // Ottieni l'id (PK) della row nel database, questo è incapsulato
        // nell'oggetto IdFirstnameItem della prima colonna della row selezionata
        // nella JTable (-1 se nessuna selezione è attiva).
        // Id della row selezionata nella JTable.
        int selRow = this.personDataTable.getSelectedRow();
        if (selRow < 0) {
            return;
        }

        // Ritorna l'oggetto IdFirstnameItem (nella prima colonna).
        DefaultTableModel dtm = (DefaultTableModel) this.personDataTable.getModel();
        IdFirstnameItem idItem = (IdFirstnameItem) dtm.getValueAt(selRow,
                PersonDBFrame.FIRSTNAME_TABLE_COLUMN);

        // Modifica la row del DB (identificata dalla PK) corrispondente alla
        // row attualmente selezionata nella JTable.
        String sql = "UPDATE person SET firstname = ?, lastname = ?,"
                + " email = ?, address = ?"
                + " WHERE id = ?";
        try ( PreparedStatement pstmt = this.conn.prepareStatement(sql)) {
            // Modifica 'firstname', 'lastname', 'email' e 'address' (nel
            // database) con i valori stringa dei relativi JTextField.
            pstmt.setString(1, this.firstnameTextField.getText());
            pstmt.setString(2, this.lastnameTextField.getText());
            pstmt.setString(3, this.emailTextField.getText());
            pstmt.setString(4, this.addressTextField.getText());
            pstmt.setInt(5, idItem.getId());  // PK per la clusola WHERE.

            // Esegui la query di UPDATE.
            pstmt.executeUpdate();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage(),
                    "Person List",
                    JOptionPane.ERROR_MESSAGE);
        }

        // Aggiorna il contenuto della JTable (con i nuovi dati del DB).
        this.refreshTableContent();
    }//GEN-LAST:event_updateButtonActionPerformed

