package ialptabellinadel3ciclowhile;


public class IalpTabellinaDel3CicloWhile
{


    public static void main(String[] args)
    {
        int j = 1;//Inizzializzazione
        
        while(j<=10)
        {
            System.out.println(3 + "*" + j + "=" + (3*j));
            j++;//Aggiornamento j+1
            
            /*
            run:
            3*1=3
            3*2=6
            3*3=9
            3*4=12
            3*5=15
            3*6=18
            3*7=21
            3*8=24
            3*9=27
            3*10=30
            */
            
        }
        
      
    }
    
}
