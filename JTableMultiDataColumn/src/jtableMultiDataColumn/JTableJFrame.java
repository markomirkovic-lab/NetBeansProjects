    public JTableJFrame() {
        initComponents();

        // Listener per l'evento del cambio di selezione nella JTable.
        ListSelectionModel selectionModel = this.dataTable.getSelectionModel();
        selectionModel.addListSelectionListener(new ListSelectionListener() {
            @Override
            public void valueChanged(ListSelectionEvent e) {
                // Gestione Evento.
                // L'utente ha selezionato una nuova item della JTable.
                // Dalla documentazione di Java:
                // Returns whether or not this is one in a series of multiple
                // events, where changes are still being made.
                // See the documentation for
                //   ListSelectionModel.setValueIsAdjusting(boolean)
                // for more details on how this is used.
                // Returns: true if this is one in a series of multiple events,
                //          where changes are still being made.
                if (e.getValueIsAdjusting()) return;

                updateGUI();

                // Ottieni l'indice della row selezionata nella JTable (-1 se
                // nessuna selezione è attiva).
                int selRow = dataTable.getSelectedRow();
                if (selRow < 0) return;

                // Ottieni il DefaultTableModel della JTable.
                DefaultTableModel dtm = (DefaultTableModel) dataTable.getModel();

                // Una selezione è attiva, copia i dati della row selezionata
                // nei JTextFiels.
                // I campi id e firstName si trovano nell'oggetto IdFirstNameData
                // memorizzato nella cella della prima colonna.
                IdFirstNameData idFirst = (IdFirstNameData) dtm.getValueAt(selRow,
                                                                           JTableJFrame.ID_FIRSTNAME_COLUMN);
                idTextField.setText(idFirst.getId() + "");
                firstTextField.setText(idFirst.getFirstName());

                // La stringa del lastName è memorizzata (come String) nella
                // seconda colonna.
                lastTextField.setText((String) dtm.getValueAt(selRow,
                                                              JTableJFrame.LASTNAME_COLUMN));
            }
        });

        this.updateGUI();
    }

    private void updateGUI() {
        int id = -1;
        try {
            id = Integer.parseInt(this.idTextField.getText());
        } catch (NumberFormatException ex) { }

        boolean bDataOk = id > 0 && !this.firstTextField.getText().isBlank() &&
                                    !this.lastTextField.getText().isBlank();
        int selRow = this.dataTable.getSelectedRow();

        this.insertButton.setEnabled(bDataOk);
        this.deleteButton.setEnabled(selRow >= 0);
    }

