    private void insertButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertButtonActionPerformed
        int id = -1;
        try {
            id = Integer.parseInt(this.idTextField.getText());
        } catch (NumberFormatException ex) { }
        String firstName = this.firstTextField.getText().trim();
        String lastName = this.lastTextField.getText().trim();

        if (id <= 0 || firstName.isBlank() || lastName.isBlank()) return;

        Object[] rowData = {
            // Memorizza id e firstName nella cella della prima colonna.
            new IdFirstNameData(id, firstName),
            lastName  // Memorizza il lastName nella cella della seconda colonna.
        };

        DefaultTableModel dtm = (DefaultTableModel) this.dataTable.getModel();

        // Inserisci una nuova row con i dati dei JTextField.
        dtm.addRow(rowData);
    }//GEN-LAST:event_insertButtonActionPerformed

    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        int selRow = this.dataTable.getSelectedRow();
        if (selRow < 0) return;

        // Elimina la row selezionata nella JTable.
        DefaultTableModel dtm = (DefaultTableModel) this.dataTable.getModel();
        dtm.removeRow(selRow);
    }//GEN-LAST:event_deleteButtonActionPerformed

