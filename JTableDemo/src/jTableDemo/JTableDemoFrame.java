    public JTableDemoFrame() {
        initComponents();

        // Listener per l'evento del cambio di selezione nella JTable.
        ListSelectionModel selectionModel = this.listTable.getSelectionModel();
        selectionModel.addListSelectionListener(new ListSelectionListener() {
            @Override
            public void valueChanged(ListSelectionEvent e) {
                // Gestione  Evento ///////////////////////////////////
                // L'utente ha selezionato una nuova item della JTable.
                // Dalla documentazione di Java:
                // Returns whether or not this is one in a series of multiple
                // events, where changes are still being made.
                // See the documentation for
                //   ListSelectionModel.setValueIsAdjusting(boolean)
                // for more details on how this is used.
                // Returns: true if this is one in a series of multiple events,
                //          where changes are still being made.
                if (e.getValueIsAdjusting()) return;

                // Ottieni l'indice della row selezionata nella JTable (-1 se
                // nessuna selezione è attiva).
                int selRow = listTable.getSelectedRow();
                if (selRow < 0) return;

                // Ottieni il DefaultTableModel della JTable.
                DefaultTableModel dtm = (DefaultTableModel) listTable.getModel();

                // Una selezione è attiva, copia i dati della row selezionata
                // nei JTextFiels.
                int id = (int) dtm.getValueAt(selRow,
                                              JTableDemoFrame.ID_TABLE_COLUMN);
                idTextField.setText(id + "");
                firstnameTextField.setText((String) dtm.getValueAt(selRow,
                                           JTableDemoFrame.FIRSTNAME_TABLE_COLUMN));
                lastnameTextField.setText((String) dtm.getValueAt(selRow,
                                          JTableDemoFrame.LASTNAME_TABLE_COLUMN));

                // Aggiorna lo stato di enabled/disabled dei button della GUI.
                updateGUI();
            }
        });

        // Aggiorna lo stato di enabled/disabled dei button della GUI.
        this.updateGUI();
    }

    // Metodo di utility privato.
    private void updateGUI() {
        // Ottieni l'indice della row selezionata nella JTable (-1 se nessuna
        // selezione è attiva) e il numero di rows corrente.
        int selRow = this.listTable.getSelectedRow();
        int rowsCount = this.listTable.getRowCount();

        // Determina se il contenuto di tutti i JTextField è valido.
        // Il valore dell'id deve essere un numero maggiore o uguale a zero.
        boolean isNumeric = false;
        try {
            int val = Integer.parseInt(this.idTextField.getText());
            if (val >= 0) isNumeric = true;
        } catch (NumberFormatException ex) { }

        // I valori dell'id, del firstname e del lastname devono essere validi.
        boolean isValidEntry = isNumeric &&
                               !this.firstnameTextField.getText().isBlank() &&
                               !this.lastnameTextField.getText().isBlank();

        // Abilita/disabilita i button della GUI in funzione dello stato della
        // JTable (selected item) e del contenuto dei JTextField.
        this.insertNewButton.setEnabled(isValidEntry);
        this.modifySelectedButton.setEnabled(selRow >= 0 && isValidEntry);
        this.deleteSelectedButton.setEnabled(selRow >= 0);
        this.deleteAllButton.setEnabled(rowsCount > 0);
    }

