    private void insertNewButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertNewButtonActionPerformed
        // Gestione  Evento ///////////////////////
        // L'utente ha cliccato il button "Insert".

        // Ottieni il valore dell'id.
        int id = -1;
        try {
            id = Integer.parseInt(this.idTextField.getText());
        } catch (NumberFormatException ex) { }

        // L'id deve essere numerico e maggiore o uguale a 0.
        if (id < 0) return;

        // Imposta l'array di Object con i dati della row da inserire.
        // Un elemento Object può essere impostato direttamente con qualsiasi
        // tipo di dato, questa operazione si chiama "boxing".
        Object[] rowData = {
            id,
            this.firstnameTextField.getText(),
            this.lastnameTextField.getText()
        };

        // Ottieni il DefaultTableModel della JTable.
        DefaultTableModel dtm = (DefaultTableModel) this.listTable.getModel();

        // Inserisci una nuova row con i dati dei JTextField.
        dtm.addRow(rowData);
    }//GEN-LAST:event_insertNewButtonActionPerformed

    private void modifySelectedButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modifySelectedButtonActionPerformed
        // Gestione  Evento ////////////////////////////////
        // L'utente ha cliccato il button "Modify Selected".

        // Ottieni il valore dell'id.
        int id = -1;
        try {
            id = Integer.parseInt(this.idTextField.getText());
        } catch (NumberFormatException ex) { }

        // L'id deve essere numerico e maggiore o uguale a zero.
        if (id < 0) return;

        // Ottieni l'indice della row selezionata nella JTable (-1 se nessuna
        // selezione è attiva).
        int selRow = this.listTable.getSelectedRow();
        if (selRow < 0) return;

        // Modifica i valori delle colonne della row selezionata.
        DefaultTableModel dtm = (DefaultTableModel) this.listTable.getModel();
        dtm.setValueAt(id, selRow, JTableDemoFrame.ID_TABLE_COLUMN);
        dtm.setValueAt(this.firstnameTextField.getText(), selRow,
                       JTableDemoFrame.FIRSTNAME_TABLE_COLUMN);
        dtm.setValueAt(this.lastnameTextField.getText(), selRow,
                       JTableDemoFrame.LASTNAME_TABLE_COLUMN);
    }//GEN-LAST:event_modifySelectedButtonActionPerformed

    private void deleteSelectedButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteSelectedButtonActionPerformed
        // Gestione  Evento ////////////////////////////////
        // L'utente ha cliccato il button "Delete Selected".

        // Ottieni l'indice della row selezionata nella JTable (-1 se nessuna
        // selezione è attiva).
        int selRow = this.listTable.getSelectedRow();
        if (selRow < 0) return;

        // Ottieni il DefaultTableModel della JTable ed elimina la row selezionata.
        DefaultTableModel dtm = (DefaultTableModel) this.listTable.getModel();
        dtm.removeRow(selRow);
    }//GEN-LAST:event_deleteSelectedButtonActionPerformed

    private void deleteAllButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteAllButtonActionPerformed
        // Gestione  Evento ///////////////////////////
        // L'utente ha cliccato il button "Delete All".

        // Ottieni il DefaultTableModel della JTable ed elimina tutte le row
        // della JTable.
        DefaultTableModel dtm = (DefaultTableModel) this.listTable.getModel();
        dtm.setRowCount(0);
    }//GEN-LAST:event_deleteAllButtonActionPerformed

