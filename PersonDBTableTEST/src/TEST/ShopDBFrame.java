    private void updateGUI() {
        // Determina lo stato dei 3 JTextField e se la JTable ha una selezione.
        boolean isValidData = !this.nomeTextField.getText().isBlank()
                && !this.fornitoreTextField.getText().isBlank()
                && !this.quantitaTextField.getText().isBlank()
                && !this.prezzoTextField.getText().isBlank();
        boolean hasSelection = this.shopDataTable.getSelectedRow() >= 0;

        // Aggiorna lo stato di 'enabled' dei button.
        this.insertButton.setEnabled(isValidData);
        this.updateButton.setEnabled(isValidData && hasSelection);
        this.deleteButton.setEnabled(hasSelection);
    }

    private void createOrOpenDB() {
        try {
            Class.forName("org.sqlite.JDBC");

            // Apre la connessione con il database, se il db non esiste, viene creato.
            this.conn = DriverManager.getConnection("jdbc:sqlite:Shop.db");//Shop --------------

            // Crea la tabella 'person' se non esiste ancora.
            try ( Statement stmt = this.conn.createStatement()) {
                String sql = "CREATE TABLE IF NOT EXISTS article ("
                        + " id INTEGER NOT NULL,"
                        + " nome TEXT NOT NULL,"
                        + " fornitore TEXT NOT NULL,"
                        + " quantita INTEGER NOT NULL,"
                        + " prezzo  DOUBLE NOT NULL,"
                        + " PRIMARY KEY (id))";
                stmt.executeUpdate(sql);
            }
        } catch (ClassNotFoundException | SQLException ex) {
            String err = ex.getMessage().trim();
            if (ex instanceof ClassNotFoundException) {
                err = "Class '" + err + "' not found.";
            }

            JOptionPane.showMessageDialog(null,
                    err + "\n\nTerminating the application!",
                    "Article List",
                    JOptionPane.ERROR_MESSAGE);

            // Termina l'applicazione, errore non rimediabile.
            this.dispatchEvent(new WindowEvent(this, WindowEvent.WINDOW_CLOSING));
        }
    }
    
    
