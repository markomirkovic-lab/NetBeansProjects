    public ShopDBFrame() {
        initComponents();

        // Listener per l'evento del cambio di selezione nella JTable.
        ListSelectionModel selectionModel = this.shopDataTable.getSelectionModel();
        selectionModel.addListSelectionListener(new ListSelectionListener() {
            @Override
            public void valueChanged(ListSelectionEvent e) {
                // L'utente ha selezionato una nuova item della JTable.
                // Dalla documentazione di Java:
                // Returns whether or not this is one in a series of multiple
                // events, where changes are still being made.
                // See the documentation for
                //   ListSelectionModel.setValueIsAdjusting(boolean)
                // for more details on how this is used.
                // Returns: true if this is one in a series of multiple events,
                //          where changes are still being made.
                if (e.getValueIsAdjusting()) {
                    return;
                }

                // Aggiorna lo stato della GUI.
                updateGUI();

                // Ottieni l'indice della row selezionata nella JTable (-1 se
                // nessuna selezione è attiva).
                int selRow = shopDataTable.getSelectedRow();
                if (selRow < 0) {
                    return;
                }

                // Ottieni il DefaultTableModel della JTable.
                // Nota: a differenza delle ultime 3 colonne (che contengono
                //       direttamente le stringhe di 'lastname', 'email' e
                //       'address'), la prima colonna (firstname) contiene un
                //       oggetto di tipo IdFirstnameItem, questo include la
                //       stringa per il 'firstname' e l'id della corrispondente
                //       row nel DB (la PK).
                //       L'id deve essere memorizzato (serve per le queries), ma
                //       non visualizzato (PK surrogata), vedi metodo toString()
                //       della classe IdFirstnameItem che, dei due dati, mostra
                //       appunto solo il 'firstname'.
                DefaultTableModel dtm = (DefaultTableModel) shopDataTable.getModel();

                // Una selezione è attiva nella JTable, copia i dati della row
                // selezionata nei relativi JTextFiels.
                IdNameItem idNome = (IdNameItem) dtm.getValueAt(selRow,
                        ShopDBFrame.NOME_TABLE_COLUMN);

                // Il 'firstname' è estratto dall'oggetto firstnameItem, gli
                // altri dati sono estratti direttamente dalle celle come stringhe.
                nomeTextField.setText(idNome.getName());
                fornitoreTextField.setText((String) dtm.getValueAt(selRow, ShopDBFrame.FORNITORE_TABLE_COLUMN));
                quantitaTextField.setText((String) dtm.getValueAt(selRow, ShopDBFrame.QUANTITA_TABLE_COLUMN));
                prezzoTextField.setText((String) dtm.getValueAt(selRow, ShopDBFrame.PREZZO_TABLE_COLUMN));
            }
        });

        // Crea o apri il database.
        this.createOrOpenDB();

        // Popola la JTable.
        this.refreshTableContent();

        // Inizializza lo stato della GUI.
        this.updateGUI();
    }

